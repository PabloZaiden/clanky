import { useCallback, useMemo, useState, type ReactNode } from "react";
import logoSvgPath from "../../favicon.svg" with { type: "file" };
import {
  useToast,
  WebAppRoot,
  type WebAppRoute,
} from "@pablozaiden/webapp/web";
import {
  buildShellRoutes,
  type ShellRouteCompositionContext,
} from "./shell-route-composition";
import {
  buildShellSidebarComposition,
  type ShellSidebarActionHandlers,
} from "./shell-sidebar-composition";
import { buildShellSettingsSections } from "./shell-settings-composition";
import { ShellHeaderActionsContext } from "./shell-header-actions";
import { useShellActions } from "./use-shell-actions";
import { HOME_ROUTE, useShellNavigation } from "./use-shell-navigation";
import {
  RouteHeaderTitle,
  useShellHeader,
  type RegisteredHeaderActions,
} from "./use-shell-header";
import { useShellResources } from "./use-shell-resources";

export function AppShell() {
  const toast = useToast();
  const [route, setRoute] = useState<WebAppRoute>(HOME_ROUTE);
  const [registeredHeaderActions, setRegisteredHeaderActions] = useState<RegisteredHeaderActions | null>(null);
  const registerHeaderActions = useCallback((owner: symbol, actions: ReactNode) => {
    setRegisteredHeaderActions({ owner, actions });
  }, []);
  const unregisterHeaderActions = useCallback((owner: symbol) => {
    setRegisteredHeaderActions((current) => current?.owner === owner ? null : current);
  }, []);
  const shellHeaderActionsContextValue = useMemo(
    () => ({ register: registerHeaderActions, unregister: unregisterHeaderActions }),
    [registerHeaderActions, unregisterHeaderActions],
  );
  const {
    chats,
    chatsLoading,
    refreshChats,
    createChat,
    importExistingChat,
    createSshServerChat,
    updateChat,
    markChatDone,
    agents,
    tasks,
    tasksLoading,
    refreshTasks,
    markTaskStarting,
    clearOptimisticTaskStart,
    createTask,
    updateTask,
    purgeTask,
    purgeArchivedWorkspaceTasks,
    sessions,
    refreshSshSessions,
    createSession,
    updateWorkspaceSshSession,
    deleteWorkspaceSshSession,
    servers,
    sessionsByServerId,
    refreshSshServers,
    createServer,
    updateServer,
    deleteServer,
    createStandaloneSession,
    updateStandaloneSession,
    deleteStandaloneSession,
    workspaces,
    workspacesLoading,
    workspacesSaving,
    workspaceError,
    refreshWorkspaces,
    createWorkspace,
    updateWorkspace,
    deleteWorkspace,
    pullLatestChanges,
    quickChatSettings,
    schedulerTimezone,
    markdownPreference,
    mesh,
    fullTreePreference,
    privateItemsPreference,
    dashboardData,
    provisioning,
    workspaceGroups,
    allWorkspaceGroups,
    sidebarWorkspaceGroups,
    serverNodes,
    quickChatWorkspace,
    quickChatUnavailableReason,
    shellLoading,
    shellErrors,
    taskId,
    chatId,
    composeKind,
    selectedTask,
    selectedChat,
    selectedWorkspace,
    selectedServer,
    composeWorkspace,
    composeServer,
    selectedAgent,
  } = useShellResources(route);

  const {
    webAppRootRef,
    handleWebRouteChange,
    navigateWithinShell,
  } = useShellNavigation({
    setRoute,
  });

  const {
    workspaceCreate,
    workspaceSettings,
    composeState,
    selectedChatActions,
    dialogs,
    pullingLatestWorkspaceIds,
    archivingWorkspaceIds,
    pullLatestWorkspaceChanges,
    toggleWorkspaceArchived,
    handleSidebarMarkChatDone,
    toggleTaskPrivate,
    toggleChatPrivate,
    toggleAgentPrivate,
    toggleWorkspacePrivate,
    toggleWorkspaceSshSessionPrivate,
    toggleSshServerPrivate,
    toggleStandaloneSshSessionPrivate,
    stopSidebarTask,
  } = useShellActions({
    route,
    navigateWithinShell,
    servers,
    provisioning,
    createWorkspace,
    refreshWorkspaces,
    workspaceGroups: allWorkspaceGroups,
    purgeArchivedWorkspaceTasks,
    pullLatestChanges,
    updateWorkspace,
    createTask,
    refreshTasks,
    dashboardData,
    toast,
    markChatDone,
    selectedChat,
    refreshChats,
    updateChat,
    agents,
    updateTask,
    updateWorkspaceSshSession,
    updateStandaloneSession,
    updateServer,
    refreshSshServers,
    deleteWorkspaceSshSession,
    deleteStandaloneSession,
    createChat,
    quickChatSettings,
    quickChatWorkspace,
  });

  const routes = useMemo(() => buildShellRoutes({
    shellLoading,
    shellErrors,
    navigateWithinShell,
    tasks,
    chats,
    workspaces,
    sessions,
    servers,
    sessionsByServerId,
    serverNodes,
    workspaceGroups,
    sidebarWorkspaceGroups,
    workspacesLoading,
    workspacesSaving,
    workspaceError,
    refreshTasks,
    markTaskStarting,
    clearOptimisticTaskStart,
    refreshChats,
    purgeTask,
    refreshSshSessions,
    refreshSshServers,
    refreshWorkspaces,
    createSession,
    createStandaloneSession,
    createServer,
    updateServer,
    deleteServer,
    deleteWorkspace,
    dashboardData,
    schedulerTimezone: schedulerTimezone.timezone,
    agents,
    editingAgentId: dialogs.editingAgentId,
    onCancelAgentEdit: dialogs.cancelAgentEdit,
    onSavedAgentEdit: dialogs.handleAgentSaved,
    composeActionState: composeState.composeActionState,
    setComposeActionState: composeState.setComposeActionState,
    handleTaskSubmit: composeState.handleTaskSubmit,
    createChat,
    importExistingChat,
    createSshServerChat,
    workspaceCreate,
    workspaceSettings,
    provisioning,
    toast,
    showPrivateItems: privateItemsPreference.showPrivateItems,
  } satisfies ShellRouteCompositionContext), [
    agents,
    dialogs.cancelAgentEdit,
    chats,
    composeState.composeActionState,
    composeState.handleTaskSubmit,
    composeState.setComposeActionState,
    createChat,
    createServer,
    createSession,
    createSshServerChat,
    createStandaloneSession,
    dashboardData,
    deleteServer,
    deleteWorkspace,
    dialogs.editingAgentId,
    dialogs.handleAgentSaved,
    importExistingChat,
    navigateWithinShell,
    privateItemsPreference.showPrivateItems,
    provisioning,
    purgeTask,
    refreshChats,
    refreshSshServers,
    refreshSshSessions,
    refreshTasks,
    markTaskStarting,
    clearOptimisticTaskStart,
    refreshWorkspaces,
    schedulerTimezone.timezone,
    serverNodes,
    servers,
    sessions,
    sessionsByServerId,
    shellErrors,
    shellLoading,
    sidebarWorkspaceGroups,
    tasks,
    toast,
    updateServer,
    workspaceCreate,
    workspaceError,
    workspaceGroups,
    workspaceSettings,
    workspaces,
    workspacesLoading,
    workspacesSaving,
  ]);

  const settingsSections = useMemo(() => buildShellSettingsSections({
    quickChatSettings,
    schedulerTimezone,
    markdownPreference,
    fullTreePreference,
    privateItemsPreference,
    dashboardData,
    workspaces,
    workspacesLoading,
    refreshTasks,
    mesh,
  }), [
    dashboardData,
    fullTreePreference,
    markdownPreference,
    mesh,
    privateItemsPreference,
    quickChatSettings,
    refreshTasks,
    schedulerTimezone,
    workspaces,
    workspacesLoading,
  ]);

  const sidebarComposition = useMemo(() => buildShellSidebarComposition({
    sidebarWorkspaceGroups,
    serverNodes,
    workspaces,
    agents: agents.agents,
    handlers: {
      route,
      selectedChat,
      selectedChatActions,
      navigateWithinShell,
      onError: (message) => toast.error(message),
      toggleTaskPrivate,
      toggleChatPrivate,
      markChatDone: handleSidebarMarkChatDone,
      toggleAgentPrivate,
      toggleWorkspacePrivate,
      toggleWorkspaceSshSessionPrivate,
      toggleSshServerPrivate,
      toggleStandaloneSshSessionPrivate,
      stopSidebarTask,
      openRenameSshSession: dialogs.openRenameSshSession,
      openDeleteSshSession: dialogs.openDeleteSshSession,
      pullLatestWorkspaceChanges,
      pullingLatestWorkspaceIds,
      toggleWorkspaceArchived,
      archivingWorkspaceIds,
      setEditingAgentId: dialogs.setEditingAgentId,
      setDeleteAgentTarget: dialogs.setDeleteAgentTarget,
      setPurgeAgentTarget: dialogs.setPurgeAgentTarget,
      agents,
      showPrivateItems: privateItemsPreference.showPrivateItems,
    } satisfies ShellSidebarActionHandlers,
    quickChatUnavailableReason,
    quickChatCreating: dialogs.quickChatCreating,
    onQuickChat: () => void dialogs.handleQuickChat(),
  }), [
    agents,
    archivingWorkspaceIds,
    dialogs.handleQuickChat,
    navigateWithinShell,
    dialogs.openDeleteSshSession,
    dialogs.openRenameSshSession,
    privateItemsPreference.showPrivateItems,
    pullLatestWorkspaceChanges,
    pullingLatestWorkspaceIds,
    dialogs.quickChatCreating,
    quickChatUnavailableReason,
    route,
    selectedChat,
    selectedChatActions,
    serverNodes,
    dialogs.setDeleteAgentTarget,
    dialogs.setEditingAgentId,
    dialogs.setPurgeAgentTarget,
    sidebarWorkspaceGroups,
    stopSidebarTask,
    toast,
    toggleAgentPrivate,
    toggleChatPrivate,
    handleSidebarMarkChatDone,
    toggleSshServerPrivate,
    toggleStandaloneSshSessionPrivate,
    toggleTaskPrivate,
    toggleWorkspaceArchived,
    toggleWorkspacePrivate,
    toggleWorkspaceSshSessionPrivate,
    workspaces,
  ]);
  const header = useShellHeader({
    route,
    headerNodes: sidebarComposition.headerNodes,
    registeredHeaderActions,
    navigateWithinShell,
    taskId,
    chatId,
    composeKind,
    selectedTask,
    selectedChat,
    selectedWorkspace,
    composeWorkspace,
    composeServer,
    selectedServer,
    selectedAgent,
    tasksLoading,
    chatsLoading,
    agents,
    servers,
    sessions,
    sessionsByServerId,
    workspaces,
    editingAgentId: dialogs.editingAgentId,
    composeActionState: composeState.composeActionState,
  });

  return (
    <ShellHeaderActionsContext.Provider value={shellHeaderActionsContextValue}>
      <WebAppRoot
        ref={webAppRootRef}
        appName="Clanky"
        appIcon={logoSvgPath}
        homeRoute={HOME_ROUTE}
        sidebar={sidebarComposition.sidebar}
        routes={routes}
        onRouteChange={handleWebRouteChange}
        header={{
          renderTitle: ({ defaultTitle }) => <RouteHeaderTitle model={header.headerModel} defaultTitle={defaultTitle} />,
          renderActions: () => header.directHeaderActions,
          getActions: () => header.headerActions,
        }}
        settings={{ sections: settingsSections }}
        version={dashboardData.version ?? undefined}
      />
      {dialogs.modals}
    </ShellHeaderActionsContext.Provider>
  );
}

export default AppShell;
